export const DICT = { 'zh-TW': zh, en };
let lang = 'zh-TW';

export function initLang(saved) {
  if (saved && DICT[saved]) lang = saved;
  else lang = /^zh/i.test(globalThis.navigator?.language ?? '') ? 'zh-TW' : 'en';
}
export const getLang = () => lang;
export function setLang(l) {
  if (DICT[l]) lang = l;
}

export function t(key, params = {}) {
  const s = DICT[lang][key] ?? zh[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? String(params[k]) : m));
}

export const hasText = (key) => key in zh;

export function applyI18n(root) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
}
